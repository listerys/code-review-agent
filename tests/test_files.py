from code_review_agent.index.files import (
    boilerplate_exclusions,
    classify_path,
    content_exclusion,
    is_test_path,
    module_name_for,
    source_roots,
    template_name_for,
)


def reason(path, size=100):
    return classify_path(path, size, [], 4_000_000).excluded_reason


def test_exclusion_rules():
    assert reason("node_modules/x/index.js") == "vendored_or_build_dir"
    assert reason(".env.production") == "secret_file"
    assert reason("poetry.lock") == "lockfile"
    assert reason("app/static/lib/moment.js") == "third_party_asset"
    assert reason("app/static/app.min.js") == "minified"
    assert reason("app/static/big.js", size=900_000) == "too_large"
    assert reason("shop/views.py") is None
    assert classify_path("shop/migrations/0002_x.py", 10, [], 10**6).handler == "migration"
    assert classify_path("shop/templates/shop/a.html", 10, [], 10**6).handler == "template"
    assert reason("shop/views.py") is None and classify_path("x.py", 1, ["x.py"], 10).excluded_reason == "config_exclude"


def test_content_exclusions_detect_binary_generated_and_pii():
    python = classify_path("a.py", 10, [], 10**6)
    assert content_exclusion(python, b"\x00\x01binary") == "binary"
    assert content_exclusion(python, b"# @generated by protoc\nx = 1\n") == "generated"
    fixture = classify_path("app/fixtures/users.json", 10, [], 10**6)
    people = b'[{"email": "jane@gmail.com"}, {"email": "bob@yahoo.com"}, {"email": "amy@corp.io"}]'
    assert content_exclusion(fixture, people) == "pii_fixture"
    assert content_exclusion(fixture, b'[{"email": "a@example.com"}]') is None


def test_boilerplate_families_keep_one_representative():
    candidates = [(f"site/urls/tenant{index}.py", "same") for index in range(25)]
    candidates.append(("site/urls/special.py", "different"))
    excluded = boilerplate_exclusions(candidates, 20)
    assert len(excluded) == 24
    assert "site/urls/tenant0.py" not in excluded
    assert "site/urls/special.py" not in excluded


def test_module_names_support_namespace_packages_and_src_layout():
    roots = source_roots(["manage.py", "nycbbl/openai/tasks.py", "src/pkg/__init__.py", "backend/manage.py"])
    assert module_name_for("nycbbl/openai/tasks.py", roots) == "nycbbl.openai.tasks"
    assert module_name_for("src/pkg/__init__.py", roots) == "pkg"
    assert module_name_for("backend/app/views.py", roots) == "app.views"


def test_path_helpers():
    assert is_test_path("shop/tests/test_refunds.py")
    assert is_test_path("conftest.py")
    assert not is_test_path("shop/services/refunds.py")
    assert template_name_for("shop/templates/emails/receipt.html") == "emails/receipt.html"
