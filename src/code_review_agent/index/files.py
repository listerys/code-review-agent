GENERATED_MARKERS = re.compile(r"(?i)(@generated|do not edit|autogenerated|auto-generated|code generated by)")
EMAIL_PATTERN = re.compile(r"[A-Za-z0-9._%+\-]+@[A-Za-z0-9.\-]+\.[A-Za-z]{2,}")
SAFE_EMAIL_DOMAINS = re.compile(r"(?i)@(example\.(com|org|net)|test\.com|localhost|test|invalid|email\.com|domain\.com)$")
PHONE_PATTERN = re.compile(r"\+?\d[\d\-\s().]{8,}\d")
SKELETON_STRINGS = re.compile(r"(\"(?:[^\"\\\n]|\\.)*\"|'(?:[^'\\\n]|\\.)*')")
SKELETON_NUMBERS = re.compile(r"\b\d+\b")


@dataclass
class FileDecision:
    path: str
    language: str
    handler: str
    excluded_reason: str | None = None


def path_parts(path: str) -> list[str]:
    return list(PurePosixPath(path).parts)


def matches_any(path: str, patterns: list[str]) -> bool:
    name = PurePosixPath(path).name
    for pattern in patterns:
        if fnmatch.fnmatch(path, pattern) or fnmatch.fnmatch(name, pattern):
            return True
        if pattern.endswith("/**") and path.startswith(pattern[:-3] + "/"):
            return True
    return False


def is_test_path(path: str) -> bool:
    parts = path_parts(path)
    name = parts[-1]
    if name.startswith("test_") or name.endswith("_test.py") or name in ("tests.py", "conftest.py"):
        return True
    for part in parts[:-1]:
        if part in ("tests", "test", "functional_tests", "testing"):
            return True
    return False


def is_migration_path(path: str) -> bool:
    parts = path_parts(path)
    return len(parts) >= 2 and parts[-2] == "migrations" and parts[-1].endswith(".py") and parts[-1] != "__init__.py"


def is_fixture_path(path: str) -> bool:
    parts = path_parts(path)
    suffix = PurePosixPath(path).suffix.lower()
    if suffix not in (".json", ".yaml", ".yml", ".xml", ".csv", ".sql"):
        return False
    return "fixtures" in parts or "fixture" in parts[-1].lower()


def is_settings_module(path: str) -> bool:
    parts = path_parts(path)
    name = parts[-1]
    if not name.endswith(".py"):
        return False
    stem = name[:-3]
    if stem.startswith("settings") or stem in ("celery", "celeryconfig", "wsgi", "asgi"):
        return True
    return len(parts) >= 2 and parts[-2] == "settings"


def is_template_path(path: str) -> bool:
    suffix = PurePosixPath(path).suffix.lower()
    if suffix in TEMPLATE_EXTENSIONS:
        return True
    parts = path_parts(path)
    return suffix in (".txt", ".xml") and "templates" in parts


def classify_path(path: str, size: int, exclude_patterns: list[str], max_bytes: int) -> FileDecision:
    parts = path_parts(path)
    name = parts[-1]
    suffix = PurePosixPath(path).suffix.lower()

    for part in parts[:-1]:
        if part in EXCLUDED_DIRECTORIES or part.endswith(".egg-info"):
            return FileDecision(path, "none", "none", "vendored_or_build_dir")
    if matches_any(path, SECRET_FILE_PATTERNS):
        return FileDecision(path, "none", "none", "secret_file")
    if name in LOCKFILES:
        return FileDecision(path, "none", "none", "lockfile")
    if exclude_patterns and matches_any(path, exclude_patterns):
        return FileDecision(path, "none", "none", "config_exclude")
    if name.endswith((".min.js", ".min.css", ".map")) or ".bundle." in name:
        return FileDecision(path, "none", "none", "minified")
    if size > max_bytes:
        return FileDecision(path, "none", "none", "too_large")

    if suffix == ".py":
        if is_migration_path(path):
            return FileDecision(path, "python", "migration")
        return FileDecision(path, "python", "python")
    if is_fixture_path(path):
        return FileDecision(path, "data", "fixture")
    if is_template_path(path):
        return FileDecision(path, "django_template", "template")
    if suffix in DOC_EXTENSIONS or name.upper().startswith(("README", "ADR")):
        return FileDecision(path, "markdown", "doc")
    if suffix in CONFIG_EXTENSIONS or name in CONFIG_FILENAMES:
        return FileDecision(path, "config", "config")
    if suffix in FALLBACK_EXTENSIONS:
        if "static" in parts[:-1] and THIRD_PARTY_ASSET_DIRECTORIES.intersection(parts[:-1]):
            return FileDecision(path, "none", "none", "third_party_asset")
        if size > FALLBACK_MAX_BYTES:
            return FileDecision(path, "none", "none", "too_large")
        return FileDecision(path, FALLBACK_EXTENSIONS[suffix], "fallback")
    return FileDecision(path, "none", "none", "unsupported_type")


def content_exclusion(decision: FileDecision, data: bytes) -> str | None:
    head = data[:8192]
    if b"\x00" in head:
        return "binary"
    text = data.decode("utf-8", "replace")
    lines = text.splitlines()
    if lines:
        longest = max(len(line) for line in lines[:400])
        average = sum(len(line) for line in lines[:400]) / min(len(lines), 400)
        if decision.handler in ("fallback", "config", "template") and (average > 300 or longest > 5000):
            return "minified"
    first_lines = "\n".join(lines[:5])
    if decision.handler in ("python", "fallback", "config") and GENERATED_MARKERS.search(first_lines):
        return "generated"
    if decision.handler == "fixture":
        if contains_personal_data(text):
            return "pii_fixture"
        if len(data) > 200_000:
            return "large_fixture"
    return None


def contains_personal_data(text: str) -> bool:
    real_emails = 0
    for match in EMAIL_PATTERN.finditer(text):
        if not SAFE_EMAIL_DOMAINS.search(match.group(0)):
            real_emails += 1
            if real_emails >= 3:
                return True
    phone_hits = len(PHONE_PATTERN.findall(text[:200_000]))
    return phone_hits >= 5


def skeleton_hash(data: bytes) -> str:
    text = data.decode("utf-8", "replace")
    text = SKELETON_STRINGS.sub('""', text)
    text = SKELETON_NUMBERS.sub("0", text)
    return hashlib.sha1(text.encode()).hexdigest()[:16]


def boilerplate_exclusions(candidates: list[tuple[str, str]], family_min: int) -> dict[str, str]:
    families: dict[tuple[str, str], list[str]] = {}
    for path, skeleton in candidates:
        directory = str(PurePosixPath(path).parent)
        families.setdefault((directory, skeleton), []).append(path)
    excluded: dict[str, str] = {}
    for members in families.values():
        if len(members) < family_min:
            continue
        members.sort()
        representative = members[0]
        for member in members[1:]:
            excluded[member] = f"boilerplate_family:{representative}:{len(members)}"
    return excluded


def source_roots(paths: list[str]) -> list[str]:
    roots = {""}
    for path in paths:
        pure = PurePosixPath(path)
        if pure.name == "manage.py" and str(pure.parent) != ".":
            roots.add(str(pure.parent))
        for index, part in enumerate(pure.parts[:-1]):
            if part == "src":
                roots.add("/".join(pure.parts[: index + 1]))
    return sorted(roots, key=len, reverse=True)


def module_name_for(path: str, roots: list[str]) -> str:
    pure = PurePosixPath(path)
    if pure.suffix != ".py":
        return path
    for root in roots:
        if root and not path.startswith(root + "/"):
            continue
        relative = path[len(root) + 1 :] if root else path
        parts = list(PurePosixPath(relative).with_suffix("").parts)
        if parts and parts[-1] == "__init__":
            parts = parts[:-1]
        if parts:
            return ".".join(parts)
        return root.replace("/", ".")
    return str(pure.with_suffix("")).replace("/", ".")


def template_name_for(path: str) -> str:
    parts = path_parts(path)
    last_templates_index = -1
    for index, part in enumerate(parts[:-1]):
        if part in ("templates", "jinja2"):
            last_templates_index = index
    if last_templates_index >= 0:
        return "/".join(parts[last_templates_index + 1 :])
    return path
